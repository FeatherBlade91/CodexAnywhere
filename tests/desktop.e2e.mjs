import test from 'node:test';
import assert from 'node:assert/strict';
import { _electron as electron } from '@playwright/test';
import { mkdtemp, writeFile, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { resolve, join } from 'node:path';
import { createServer } from 'node:net';

test('Electron desktop: isolated IPC, unified service, settings, confirmation and exit', { timeout: 90000 }, async () => {
  const dir = await mkdtemp(join(tmpdir(), 'bridge-desktop-'));
  const probe = createServer();
  await new Promise(r => probe.listen(0, '127.0.0.1', r));
  const port = probe.address().port;
  await new Promise(r => probe.close(r));
  await new Promise(r => probe.listen(0, '127.0.0.1', r));
  const unavailableProxyPort = probe.address().port;
  await new Promise(r => probe.close(r));
  await writeFile(join(dir, 'bridge.json'), JSON.stringify({ port, localKey: 'isolated-desktop-test-key', proxy: '', model: 'test-model' }));
  await writeFile(join(dir,'models.json'), JSON.stringify({models:['gpt-6-luna','gpt-6-sol','gpt-6.1-sol','gpt-6-astra','gpt-5.6-sol'].map(slug=>({slug}))}));
  const env = { ...process.env, CHATGPT_BRIDGE_STATE_DIR: dir };
  await writeFile(join(dir, 'desktop-settings.json'), JSON.stringify({ language: 'zh-CN' }));
  delete env.ELECTRON_RUN_AS_NODE;
  const options = process.env.BRIDGE_TEST_EXE ? { executablePath: resolve(process.env.BRIDGE_TEST_EXE), args: [] } : { args: [resolve('.')] };
  options.args.push(`--user-data-dir=${join(dir, 'electron-profile')}`);
  const desktop = await electron.launch({ ...options, env });
  let closed = false;
  try {
    const page = await desktop.firstWindow();
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    assert.equal(await desktop.evaluate(async () => {
      const { DatabaseSync } = process.getBuiltinModule('node:sqlite');
      const db = new DatabaseSync(':memory:');
      const value = db.prepare('SELECT 1 AS ok').get().ok; db.close(); return value;
    }), 1);
    await page.locator('#toggle-service').filter({ hasText: '启动服务' }).waitFor();
    assert.equal(await page.evaluate(() => typeof window.require), 'undefined');
    assert.equal(await page.locator('#api-key').getAttribute('type'), 'password');
    assert.equal(await page.locator('#base-url').inputValue(), `http://127.0.0.1:${port}/v1`);
    assert.equal(await page.locator('#guide-models .model-id').count(), 5);
    const example = await page.locator('#python-example').textContent();
    assert.ok(example.includes(`http://127.0.0.1:${port}/v1`));
    assert.ok(example.includes('model="gpt-6-luna"'));
    assert.ok(example.includes('reasoning_effort="low"'));
    assert.ok(!example.includes('isolated-desktop-test-key'));
    assert.equal(await page.locator('.effort-table tbody tr').count(),5);
    assert.ok(await page.locator('#python-example .syntax-string').count()>0);
    assert.equal(await page.locator('#key-rotation').inputValue(),'0');
    await page.locator('#toggle-service').click();
    await page.locator('#toggle-service').filter({ hasText: '停止服务' }).waitFor();
    const health = await fetch(`http://127.0.0.1:${port}/health`);
    assert.equal(health.status, 200);
    for (const path of ['/v1/messages', '/v1/chat/completions', '/v1/responses']) {
      const response = await fetch(`http://127.0.0.1:${port}${path}`, { method: 'POST', body: '{}' });
      assert.equal(response.status, 401, path);
    }
    await page.locator('[data-integrate="direct"]').click();
    await page.locator('#confirm-dialog').waitFor({ state: 'visible' });
    await page.locator('#confirm-dialog button[value="cancel"]').click();
    await page.locator('.nav-item[data-page="settings"]').click();
    assert.equal(await page.locator('[data-page="models"]').count(), 0);
    for (const [role, id] of Object.entries({haiku:'gpt-6-luna',sonnet:'gpt-6-sol',opus:'gpt-6.1-sol',fable:'gpt-6-astra'})) assert.equal(await page.locator('#mapping-'+role).inputValue(),id);
    await page.locator('#mapping-haiku').fill('gpt-6-sol');
    await page.locator('#mapping-form button[type="submit"]').click();
    await page.waitForFunction(() => !document.querySelector('#mapping-haiku').dataset.dirty);
    assert.equal((await page.evaluate(() => window.bridge.invoke('status'))).modelMapping.haiku, 'gpt-6-sol');
    await mkdir('test-results', { recursive: true });
    await page.screenshot({ path: 'test-results/desktop-mapping.png', fullPage: true });
    await page.locator('#proxy').fill('socks5://127.0.0.1:9');
    await page.locator('#proxy-form button[type="submit"]').click();
    await page.locator('#notice.error').waitFor({ state: 'visible' });
    await page.locator('#proxy').fill(`http://127.0.0.1:${unavailableProxyPort}`);
    await page.locator('#proxy-form button[type="submit"]').click();
    await page.waitForFunction(() => document.querySelector('#notice').textContent.includes('已保存'));
    await page.locator('.nav-item[data-page="connections"]').click();
    assert.equal(await page.locator('.quickstart').isVisible(), false);
    await page.locator('#quick-test').click();
    await page.locator('#quick-test-result.error').waitFor();
    assert.match(await page.locator('#quick-test-result').textContent(), /代理/);
    await page.locator('#quick-test:not([disabled])').waitFor();
    await page.locator('.nav-item[data-page="guide"]').click();
    await page.locator('#page-guide').waitFor();
    await page.locator('#page-guide summary').filter({ hasText: 'Python 示例' }).click();
    await page.locator('#copy-python').click();
    await page.waitForFunction(() => document.querySelector('#notice').textContent.includes('含真实密钥'));
    const copied = await desktop.evaluate(({clipboard}) => clipboard.readText());
    assert.ok(copied.includes('isolated-desktop-test-key'));
    assert.ok(copied.includes('model="gpt-6-luna"'));
    assert.ok(!(await page.locator('#python-example').textContent()).includes('isolated-desktop-test-key'));
    await desktop.evaluate(({clipboard}) => clipboard.clear());
    await page.locator('.nav-item[data-page="connections"]').click();
    await page.locator('#rotate-key').click();
    await page.locator('#confirm-action').click();
    await page.waitForFunction(() => !document.querySelector('#key-reconnect').hidden);
    assert.notEqual(await page.locator('#api-key').inputValue(),'isolated-desktop-test-key');
    await page.locator('#key-rotation').selectOption('24');
    await page.locator('#confirm-action').click();
    await page.waitForFunction(() => document.querySelector('#key-rotation').value==='24');
    await page.locator('.nav-item[data-page="guide"]').click();
    assert.equal(await page.locator('#python-example').isVisible(), true);
    await page.locator('#copy-python').click();
    await page.waitForFunction(() => document.querySelector('#notice').textContent.includes('含真实密钥'));
    const refreshedCode = await desktop.evaluate(({clipboard}) => clipboard.readText());
    assert.ok(refreshedCode.includes(await page.locator('#api-key').inputValue()));
    assert.ok(!refreshedCode.includes('isolated-desktop-test-key'));
    await desktop.evaluate(({clipboard}) => clipboard.clear());
    await page.locator('#page-guide details').evaluateAll(items => items.forEach(item => { item.open = true; }));
    await page.screenshot({ path: 'test-results/desktop-guide-expanded.png', fullPage: true });
    await page.locator('.nav-item[data-page="settings"]').click();
    await page.locator('#proxy').fill('');
    await page.locator('#proxy-form button[type="submit"]').click();
    await page.waitForFunction(() => !document.querySelector('#proxy').dataset.dirty);
    assert.equal(await page.locator('#quick-test-result').isVisible(), false, 'Saving proxy settings must clear stale test results');
    await page.locator('.nav-item[data-page="connections"]').click();
    await page.locator('#notice').waitFor({ state: 'hidden' });
    await page.locator('.nav-item[data-page="connections"]').click();
    await page.locator('#page-connections').waitFor({ state: 'visible' });
    await page.mouse.move(0, 0);
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    await mkdir('test-results', { recursive: true });
    await page.screenshot({ path: 'test-results/desktop-connections.png', fullPage: true });
    await page.setViewportSize({ width: 800, height: 640 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: 'test-results/desktop-compact.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: 'test-results/desktop-mobile.png', fullPage: true });
    await page.locator('.nav-item[data-page="guide"]').click();
    await page.locator('#page-guide details').evaluateAll(items => items.forEach(item => { item.open = false; }));
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: 'test-results/desktop-guide-mobile.png', fullPage: true });
    await page.setViewportSize({ width: 1100, height: 800 });
    await page.screenshot({ path: 'test-results/desktop-guide.png', fullPage: true });
    assert.deepEqual(errors, []);
    // Closing the native window must keep the service available in the tray.
    await desktop.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].close());
    assert.equal(await desktop.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].isVisible()), false);
    assert.equal((await fetch(`http://127.0.0.1:${port}/health`)).status, 200);
    // Reopening the application restores the existing window and worker.
    await desktop.evaluate(({ app }) => app.emit('second-instance'));
    assert.equal(await desktop.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].isVisible()), true);
    assert.equal((await fetch(`http://127.0.0.1:${port}/health`)).status, 200);
    await desktop.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].close());
    await desktop.close(); closed = true;
    await assert.rejects(fetch(`http://127.0.0.1:${port}/health`, { signal: AbortSignal.timeout(2000) }));
  } finally { if (!closed) await desktop.close(); }
});
